#include <stdio.h>

/*
    1. Основной пример сортировки выбором.

    2. Инвариант цикла while (в начале каждой итерации, перед выполнением тела цикла):

    mass - массив элементов;
    n - количество элементов в массиве;
    i - текущий индекс (0 ≤ i ≤ n-1);

    1) ∀p,q : 0 ≤ p < q < i ⇒ mass[p] ≤ mass[q]
    (первые i элементов отсортированы по неубыванию)

    2) ∀p : 0 ≤ p < i, ∀r : i ≤ r < n ⇒ mass[p] ≤ mass[r]
    (каждый элемент из отсортированной части не больше любого элемента из неотсортированной)

    3. посмотреть комментарий перед циклом while.
    4. чтобы определить время работы алгоритма проссумируем
       количетсво выполнений каждой строки в цикле while.
       количетсво приведено рядом с каждой строкой.
       так как некоторые слагаемые имеет второй порядок,
       то можно утверждать, что скорость выполнения
       квадратичная.
*/

#define ARRAY_SIZE(arr) (sizeof(arr) / sizeof((arr)[0]))

int main()
{
    // индекс элемента, который мы сейчас сортируем;
    int i = 0;
    // индекс элемента, который сравнивается с сортирующим;
    int j = 0;
    /*
        индекс элемента, который нужно поместить
        в сортируемую ячейку;
    */
    int key = 0;
    // буфер для копирования
    int buf;
    // массив, который мы хотим отсортировать;
    int mass[6] = { 31, 41, 59, 26, 41, 58 };

    /*
        Условие внешнего цикла выполняется
        столько рах сколько количетсво элементов
        в массиве.

        Мы будем проходится по всем элементам, кроме
        последнего, потому что последний будет отсортирован,
        когда мы до него дойдем.
    */
    while(i < (ARRAY_SIZE(mass) - 1))                                // n - 1;
    {
        key = i;                                                     // n - 2;

        /*
            Внутренний цикл ищет минимальный элемент в подмассиве от i+1 до конца.

            Если считать количество сравнений индексов
            (или количество выполнений тела внутреннего цикла), то:

            При i = 0 внутренний цикл делает n-1 итераций.
            При i = 1 делает n-2 итерации.
            ...
            При i = n-2 делает 1 итерацию.

            сумма в замкнутой формуле равна:
        */
        for (j = i + 1; j < ARRAY_SIZE(mass); j++)                   // ((n-1)(n-2)/2)
        {
            if (mass[key] > mass[j])                                 // ((n-1)(n-2)/2) - 1
            {
                /*
                    Так как для расчета худшего сценария мы каждый раз будем
                    заходить в это условие, то количетсво присваиваний будет
                    такое же, как проверок условий if.
                */
                key = j;                                             // ((n-1)(n-2)/2) - 1
            }
        }

        buf = mass[key];                                             // n - 2;
        mass[key] = mass[i];                                         // n - 2;
        mass[i] = buf;                                               // n - 2;

        i++;                                                         // n - 2;
    }

    for (i = 0; i < ARRAY_SIZE(mass); i++)
    {
        printf("mass[%d] = %d\n", i, mass[i]);
    }

    return 0;
}